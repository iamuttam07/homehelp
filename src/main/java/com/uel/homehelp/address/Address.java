package com.uel.homehelp.address;

import java.time.Instant;
import java.util.Locale;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import com.uel.homehelp.common.Strings;

/**
 * A place where a service can be performed. The schema is defined by Flyway
 * migration V5. The PostGIS {@code location} column is generated by the database
 * from latitude/longitude and is deliberately not mapped here; distance queries
 * use it directly.
 */
@Entity
@Table(name = "addresses")
class Address {

	@Id
	@GeneratedValue(strategy = GenerationType.UUID)
	private UUID id;

	@Column(name = "user_id", nullable = false, updatable = false)
	private UUID userId;

	@Column(length = 50)
	private String label;

	@Column(nullable = false, length = 200)
	private String line1;

	@Column(length = 200)
	private String line2;

	@Column(nullable = false, length = 100)
	private String city;

	@Column(nullable = false, length = 20)
	private String postcode;

	@Column(name = "country_code", nullable = false, length = 2)
	private String countryCode;

	@Column(nullable = false)
	private double latitude;

	@Column(nullable = false)
	private double longitude;

	@Column(name = "is_default", nullable = false)
	private boolean defaultAddress;

	@CreationTimestamp
	@Column(name = "created_at", nullable = false, updatable = false)
	private Instant createdAt;

	@UpdateTimestamp
	@Column(name = "updated_at", nullable = false)
	private Instant updatedAt;

	@Version
	private long version;

	protected Address() {
		// for JPA
	}

	Address(UUID userId, boolean defaultAddress) {
		this.userId = userId;
		this.defaultAddress = defaultAddress;
	}

	void apply(AddressRequest request) {
		this.label = Strings.trimToNull(request.label());
		this.line1 = request.line1().strip();
		this.line2 = Strings.trimToNull(request.line2());
		this.city = request.city().strip();
		this.postcode = request.postcode().strip().toUpperCase(Locale.ROOT);
		this.countryCode = request.countryCode().strip().toUpperCase(Locale.ROOT);
		this.latitude = request.latitude();
		this.longitude = request.longitude();
	}

	void setDefaultAddress(boolean defaultAddress) {
		this.defaultAddress = defaultAddress;
	}

	UUID getId() {
		return this.id;
	}

	UUID getUserId() {
		return this.userId;
	}

	String getLabel() {
		return this.label;
	}

	String getLine1() {
		return this.line1;
	}

	String getLine2() {
		return this.line2;
	}

	String getCity() {
		return this.city;
	}

	String getPostcode() {
		return this.postcode;
	}

	String getCountryCode() {
		return this.countryCode;
	}

	double getLatitude() {
		return this.latitude;
	}

	double getLongitude() {
		return this.longitude;
	}

	boolean isDefaultAddress() {
		return this.defaultAddress;
	}

	Instant getCreatedAt() {
		return this.createdAt;
	}

	Instant getUpdatedAt() {
		return this.updatedAt;
	}

}
