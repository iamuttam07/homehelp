package com.uel.homehelp.provider;

import java.time.Instant;
import java.util.Collection;
import java.util.LinkedHashSet;
import java.util.Set;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.JoinTable;
import jakarta.persistence.ManyToMany;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import com.uel.homehelp.catalog.HomeService;

/**
 * Provider-specific details, one row per PROVIDER user (same id as the user).
 * The schema is defined by Flyway migration V4.
 */
@Entity
@Table(name = "provider_profiles")
class ProviderProfile {

	@Id
	@Column(name = "user_id")
	private UUID userId;

	@Column(length = 1000)
	private String bio;

	@Column(name = "years_of_experience")
	private Integer yearsOfExperience;

	@CreationTimestamp
	@Column(name = "created_at", nullable = false, updatable = false)
	private Instant createdAt;

	@UpdateTimestamp
	@Column(name = "updated_at", nullable = false)
	private Instant updatedAt;

	/**
	 * Service area (migration V9): a base point and a radius. All three are null until
	 * set. The PostGIS {@code base_location} column is generated by the database and
	 * not mapped (see ADR 0004).
	 */
	@Column(name = "base_latitude")
	private Double baseLatitude;

	@Column(name = "base_longitude")
	private Double baseLongitude;

	@Column(name = "service_radius_km")
	private Integer serviceRadiusKm;

	/** Onboarding and approval (migration V11). See {@link OnboardingStatus} for allowed changes. */
	@Enumerated(EnumType.STRING)
	@Column(nullable = false, length = 20)
	private OnboardingStatus status = OnboardingStatus.ONBOARDING;

	@Column(name = "submitted_at")
	private Instant submittedAt;

	@Column(name = "reviewed_at")
	private Instant reviewedAt;

	/** The admin who approved or rejected the profile. */
	@Column(name = "reviewed_by")
	private UUID reviewedBy;

	@Column(name = "rejection_reason", length = 500)
	private String rejectionReason;

	/** IANA time zone of the availability windows, e.g. {@code Europe/London} (migration V10). */
	@Column(name = "time_zone", nullable = false, length = 50)
	private String timeZone = "Europe/London";

	/** The catalog services this provider offers (their skills). Table from migration V8. */
	@ManyToMany
	@JoinTable(name = "provider_services", joinColumns = @JoinColumn(name = "provider_id"),
			inverseJoinColumns = @JoinColumn(name = "service_id"))
	private Set<HomeService> services = new LinkedHashSet<>();

	/** Wrapper type so Spring Data can tell new profiles (null) from existing ones. */
	@Version
	private Long version;

	protected ProviderProfile() {
		// for JPA
	}

	ProviderProfile(UUID userId) {
		this.userId = userId;
	}

	void update(String bio, Integer yearsOfExperience) {
		this.bio = bio;
		this.yearsOfExperience = yearsOfExperience;
	}

	/** Replaces the whole set of skills. */
	void replaceServices(Collection<HomeService> services) {
		this.services.clear();
		this.services.addAll(services);
	}

	void setServiceArea(double latitude, double longitude, int radiusKm) {
		this.baseLatitude = latitude;
		this.baseLongitude = longitude;
		this.serviceRadiusKm = radiusKm;
	}

	boolean hasServiceArea() {
		return this.serviceRadiusKm != null;
	}

	Double getBaseLatitude() {
		return this.baseLatitude;
	}

	Double getBaseLongitude() {
		return this.baseLongitude;
	}

	Integer getServiceRadiusKm() {
		return this.serviceRadiusKm;
	}

	/** Whether the current status allows submitting (completeness is checked separately). */
	boolean canSubmitFromCurrentStatus() {
		return this.status == OnboardingStatus.ONBOARDING || this.status == OnboardingStatus.REJECTED;
	}

	/** ONBOARDING or REJECTED → PENDING_REVIEW. The caller checks completeness first. */
	void submit(Instant now) {
		if (!canSubmitFromCurrentStatus()) {
			throw new OnboardingConflictException("submit", this.status);
		}
		this.status = OnboardingStatus.PENDING_REVIEW;
		this.submittedAt = now;
		this.reviewedAt = null;
		this.reviewedBy = null;
		this.rejectionReason = null;
	}

	/** PENDING_REVIEW → APPROVED. */
	void approve(UUID adminId, Instant now) {
		requirePendingReview("approve");
		this.status = OnboardingStatus.APPROVED;
		this.reviewedAt = now;
		this.reviewedBy = adminId;
	}

	/** PENDING_REVIEW → REJECTED, with a reason the provider will see. */
	void reject(UUID adminId, String reason, Instant now) {
		requirePendingReview("reject");
		this.status = OnboardingStatus.REJECTED;
		this.reviewedAt = now;
		this.reviewedBy = adminId;
		this.rejectionReason = reason;
	}

	private void requirePendingReview(String action) {
		if (this.status != OnboardingStatus.PENDING_REVIEW) {
			throw new OnboardingConflictException(action, this.status);
		}
	}

	OnboardingStatus getStatus() {
		return this.status;
	}

	Instant getSubmittedAt() {
		return this.submittedAt;
	}

	Instant getReviewedAt() {
		return this.reviewedAt;
	}

	String getRejectionReason() {
		return this.rejectionReason;
	}

	void setTimeZone(String timeZone) {
		this.timeZone = timeZone;
	}

	String getTimeZone() {
		return this.timeZone;
	}

	Set<HomeService> getServices() {
		return this.services;
	}

	UUID getUserId() {
		return this.userId;
	}

	String getBio() {
		return this.bio;
	}

	Integer getYearsOfExperience() {
		return this.yearsOfExperience;
	}

	Instant getUpdatedAt() {
		return this.updatedAt;
	}

}
